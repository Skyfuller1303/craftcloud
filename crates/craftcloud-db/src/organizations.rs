//! Organizations (tenants) and organization membership. Minimal helpers.

use sqlx::{FromRow, PgPool};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::{DbError, OrgScope};

/// Role inside an organization.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OrgRole {
    /// Organization owner.
    Owner,
    /// Administrator.
    Admin,
    /// Regular member.
    Member,
}

impl OrgRole {
    fn as_str(self) -> &'static str {
        match self {
            Self::Owner => "owner",
            Self::Admin => "admin",
            Self::Member => "member",
        }
    }
}

/// Membership status.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MemberStatus {
    /// Invited, not yet accepted.
    Invited,
    /// Active member.
    Active,
    /// Disabled member.
    Disabled,
}

impl MemberStatus {
    fn as_str(self) -> &'static str {
        match self {
            Self::Invited => "invited",
            Self::Active => "active",
            Self::Disabled => "disabled",
        }
    }
}

/// Input for [`create`].
#[derive(Debug, Clone)]
pub struct NewOrganization {
    /// URL-safe slug: `^[a-z0-9][a-z0-9-]{0,62}$`.
    pub slug: String,
    /// Display name, 1 to 100 characters.
    pub name: String,
    /// Owning user.
    pub owner_user_id: Uuid,
}

/// A stored organization.
#[derive(Debug, Clone, FromRow)]
pub struct Organization {
    /// Identifier (UUID v4, generated by the application).
    pub id: Uuid,
    /// Slug.
    pub slug: String,
    /// Display name.
    pub name: String,
    /// Owning user.
    pub owner_user_id: Uuid,
    /// Creation time (UTC).
    pub created_at: OffsetDateTime,
}

/// Creates an organization. This creates the tenant itself, so it is not
/// scoped; the caller must be authorized to create organizations.
///
/// # Errors
///
/// [`DbError::UniqueViolation`] for a duplicate slug,
/// [`DbError::ForeignKeyViolation`] for an unknown owner,
/// [`DbError::CheckViolation`] for invalid values.
pub async fn create(pool: &PgPool, new: &NewOrganization) -> Result<Organization, DbError> {
    Ok(sqlx::query_as::<_, Organization>(
        "INSERT INTO organizations (id, slug, name, owner_user_id) VALUES ($1, $2, $3, $4) \
         RETURNING id, slug, name, owner_user_id, created_at",
    )
    .bind(Uuid::new_v4())
    .bind(&new.slug)
    .bind(&new.name)
    .bind(new.owner_user_id)
    .fetch_one(pool)
    .await?)
}

/// Adds a member to the scoped organization.
///
/// # Errors
///
/// [`DbError::UniqueViolation`] if the user is already a member,
/// [`DbError::ForeignKeyViolation`] for an unknown user or organization.
pub async fn add_member(
    pool: &PgPool,
    scope: &OrgScope,
    user_id: Uuid,
    role: OrgRole,
    status: MemberStatus,
) -> Result<(), DbError> {
    sqlx::query(
        "INSERT INTO organization_members (org_id, user_id, role, status) VALUES ($1, $2, $3, $4)",
    )
    .bind(scope.org_id())
    .bind(user_id)
    .bind(role.as_str())
    .bind(status.as_str())
    .execute(pool)
    .await?;
    Ok(())
}
