//! Users (instance-wide identities). Minimal helpers; the full identity
//! lifecycle arrives with the auth milestone.

use sqlx::{FromRow, PgPool};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::DbError;

/// Input for [`insert`].
#[derive(Debug, Clone)]
pub struct NewUser {
    /// Lowercase e-mail address; the database rejects non-normalized values.
    pub normalized_email: String,
    /// Display name, 1 to 100 characters.
    pub display_name: String,
}

/// A stored user. The password hash is deliberately not part of this type.
#[derive(Debug, Clone, FromRow)]
pub struct User {
    /// Identifier (UUID v4, generated by the application).
    pub id: Uuid,
    /// Lowercase e-mail address.
    pub normalized_email: String,
    /// Display name.
    pub display_name: String,
    /// Creation time (UTC).
    pub created_at: OffsetDateTime,
}

/// Inserts a user without credentials.
///
/// # Errors
///
/// [`DbError::UniqueViolation`] for a duplicate e-mail,
/// [`DbError::CheckViolation`] for an invalid value.
pub async fn insert(pool: &PgPool, new: &NewUser) -> Result<User, DbError> {
    Ok(sqlx::query_as::<_, User>(
        "INSERT INTO users (id, normalized_email, display_name) VALUES ($1, $2, $3) \
         RETURNING id, normalized_email, display_name, created_at",
    )
    .bind(Uuid::new_v4())
    .bind(&new.normalized_email)
    .bind(&new.display_name)
    .fetch_one(pool)
    .await?)
}
