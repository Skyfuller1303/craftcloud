//! Tenant-scoped workspace repository. Every function filters by the
//! `org_id` of the given [`OrgScope`] in SQL.

use sqlx::{FromRow, PgPool};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::{DbError, OrgScope};

/// Hard upper bound for [`list`]; larger requested limits are clamped.
pub const MAX_LIST_LIMIT: u32 = 200;

/// Role inside a workspace.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkspaceRole {
    /// Workspace administrator.
    Admin,
    /// Can edit content.
    Editor,
    /// Read-only.
    Viewer,
}

impl WorkspaceRole {
    fn as_str(self) -> &'static str {
        match self {
            Self::Admin => "admin",
            Self::Editor => "editor",
            Self::Viewer => "viewer",
        }
    }
}

/// Input for [`create`].
#[derive(Debug, Clone)]
pub struct NewWorkspace {
    /// URL-safe slug, unique within the organization.
    pub slug: String,
    /// Display name, 1 to 100 characters.
    pub name: String,
    /// Optional storage quota in bytes (>= 0).
    pub quota_bytes: Option<i64>,
}

/// A stored workspace.
#[derive(Debug, Clone, FromRow)]
pub struct Workspace {
    /// Identifier (UUID v4, generated by the application).
    pub id: Uuid,
    /// Owning organization.
    pub org_id: Uuid,
    /// Slug.
    pub slug: String,
    /// Display name.
    pub name: String,
    /// Optional storage quota in bytes.
    pub quota_bytes: Option<i64>,
    /// Creation time (UTC).
    pub created_at: OffsetDateTime,
}

const COLUMNS: &str = "id, org_id, slug, name, quota_bytes, created_at";

/// Creates a workspace in the scoped organization.
///
/// # Errors
///
/// [`DbError::UniqueViolation`] for a duplicate slug in this organization,
/// [`DbError::CheckViolation`] for invalid values (slug, name, negative
/// quota), [`DbError::ForeignKeyViolation`] if the organization is unknown.
pub async fn create(
    pool: &PgPool,
    scope: &OrgScope,
    new: &NewWorkspace,
) -> Result<Workspace, DbError> {
    scope.require(craftcloud_core::policy::Action::WorkspaceManage)?;
    Ok(sqlx::query_as::<_, Workspace>(&format!(
        "INSERT INTO workspaces (id, org_id, slug, name, quota_bytes) \
         VALUES ($1, $2, $3, $4, $5) RETURNING {COLUMNS}"
    ))
    .bind(Uuid::new_v4())
    .bind(scope.org_id())
    .bind(&new.slug)
    .bind(&new.name)
    .bind(new.quota_bytes)
    .fetch_one(pool)
    .await?)
}

/// Fetches one workspace. A workspace of another organization is
/// indistinguishable from a missing one (`None`).
///
/// # Errors
///
/// Database failures only.
pub async fn get(pool: &PgPool, scope: &OrgScope, id: Uuid) -> Result<Option<Workspace>, DbError> {
    Ok(sqlx::query_as::<_, Workspace>(&format!(
        "SELECT {COLUMNS} FROM workspaces WHERE org_id = $1 AND id = $2"
    ))
    .bind(scope.org_id())
    .bind(id)
    .fetch_optional(pool)
    .await?)
}

/// Lists workspaces of the scoped organization ordered by `(created_at, id)`.
/// `limit` is clamped to `1..=`[`MAX_LIST_LIMIT`].
///
/// # Errors
///
/// Database failures only.
pub async fn list(pool: &PgPool, scope: &OrgScope, limit: u32) -> Result<Vec<Workspace>, DbError> {
    let limit = i64::from(limit.clamp(1, MAX_LIST_LIMIT));
    Ok(sqlx::query_as::<_, Workspace>(&format!(
        "SELECT {COLUMNS} FROM workspaces WHERE org_id = $1 \
         ORDER BY created_at, id LIMIT $2"
    ))
    .bind(scope.org_id())
    .bind(limit)
    .fetch_all(pool)
    .await?)
}

/// Adds a workspace member. The user must already be a member of the
/// organization and the workspace must belong to the scoped organization;
/// both are enforced by composite foreign keys.
///
/// # Errors
///
/// [`DbError::ForeignKeyViolation`] if the workspace is not in this
/// organization or the user is not an organization member,
/// [`DbError::UniqueViolation`] if already a member.
pub async fn add_member(
    pool: &PgPool,
    scope: &OrgScope,
    workspace_id: Uuid,
    user_id: Uuid,
    role: WorkspaceRole,
) -> Result<(), DbError> {
    scope.require(craftcloud_core::policy::Action::WorkspaceManage)?;
    sqlx::query(
        "INSERT INTO workspace_members (org_id, workspace_id, user_id, role) \
         VALUES ($1, $2, $3, $4)",
    )
    .bind(scope.org_id())
    .bind(workspace_id)
    .bind(user_id)
    .bind(role.as_str())
    .execute(pool)
    .await?;
    Ok(())
}
