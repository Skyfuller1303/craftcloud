-- 0008: upload sessions, staged blobs and storage quota accounting (CC-F07, CC-F10).
-- Purpose: an upload session reserves quota, receives one stream into object
-- storage and leaves a verified but uncommitted ("staged") blob. Version commit
-- (compare-and-set on the file head) follows in a later migration.
-- Tenant scope: blobs reference (org_id, workspace_id) and sessions reference
-- (org_id, workspace_id, project_id, file_id) through composite foreign keys.
-- Quota: organizations.quota_bytes and workspaces.quota_bytes (NULL = unlimited,
-- ADR-0014). reserved_bytes/committed_bytes are counters maintained only inside
-- the organization-locked transaction; they can be recomputed from the sessions
-- and blobs at any time (reconciliation).
-- Restore note: forward-only; back up before applying. All foreign keys are
-- ON DELETE RESTRICT.

ALTER TABLE organizations
    ADD COLUMN quota_bytes bigint NULL,
    ADD COLUMN reserved_bytes bigint NOT NULL DEFAULT 0,
    ADD COLUMN committed_bytes bigint NOT NULL DEFAULT 0,
    ADD CONSTRAINT organizations_quota_non_negative CHECK (quota_bytes IS NULL OR quota_bytes >= 0),
    ADD CONSTRAINT organizations_usage_non_negative CHECK (reserved_bytes >= 0 AND committed_bytes >= 0);

ALTER TABLE workspaces
    ADD COLUMN reserved_bytes bigint NOT NULL DEFAULT 0,
    ADD COLUMN committed_bytes bigint NOT NULL DEFAULT 0,
    ADD CONSTRAINT workspaces_usage_non_negative CHECK (reserved_bytes >= 0 AND committed_bytes >= 0);

-- Lets upload sessions reference a file together with its tenant path.
ALTER TABLE files
    ADD CONSTRAINT files_scope_unique UNIQUE (org_id, workspace_id, project_id, id);

CREATE TABLE blobs (
    id uuid PRIMARY KEY,
    org_id uuid NOT NULL,
    workspace_id uuid NOT NULL,
    -- 32 lowercase hex characters, generated by the storage layer.
    object_key text NOT NULL,
    size_bytes bigint NOT NULL,
    sha256 bytea NOT NULL,
    state text NOT NULL DEFAULT 'staged',
    created_at timestamptz NOT NULL,
    CONSTRAINT blobs_object_key_valid CHECK (object_key ~ '^[0-9a-f]{32}$'),
    CONSTRAINT blobs_object_key_unique UNIQUE (object_key),
    CONSTRAINT blobs_size_non_negative CHECK (size_bytes >= 0),
    CONSTRAINT blobs_sha256_length CHECK (octet_length(sha256) = 32),
    CONSTRAINT blobs_state_valid CHECK (state IN ('staged', 'committed', 'orphaned')),
    CONSTRAINT blobs_workspace_fk FOREIGN KEY (org_id, workspace_id)
        REFERENCES workspaces (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT blobs_scope_unique UNIQUE (org_id, id)
);

CREATE INDEX blobs_state_idx ON blobs (state, created_at);
CREATE INDEX blobs_workspace_idx ON blobs (workspace_id, state);

CREATE TABLE upload_sessions (
    id uuid PRIMARY KEY,
    org_id uuid NOT NULL,
    workspace_id uuid NOT NULL,
    project_id uuid NOT NULL,
    file_id uuid NOT NULL,
    created_by_user_id uuid NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    declared_size bigint NOT NULL,
    declared_sha256 bytea NOT NULL,
    idempotency_key text NULL,
    -- file id, size and hash of the creating request; a replay with the same key
    -- must match, anything else is a conflict.
    request_fingerprint text NOT NULL,
    state text NOT NULL DEFAULT 'created',
    blob_id uuid NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    version bigint NOT NULL DEFAULT 1,
    CONSTRAINT upload_sessions_size_non_negative CHECK (declared_size >= 0),
    CONSTRAINT upload_sessions_sha256_length CHECK (octet_length(declared_sha256) = 32),
    CONSTRAINT upload_sessions_key_length CHECK (
        idempotency_key IS NULL OR char_length(idempotency_key) BETWEEN 1 AND 128),
    CONSTRAINT upload_sessions_state_valid CHECK (
        state IN ('created', 'receiving', 'stored', 'committed', 'aborted', 'expired', 'failed')),
    CONSTRAINT upload_sessions_blob_state CHECK (blob_id IS NULL OR state IN ('stored', 'committed', 'expired', 'aborted', 'failed')),
    CONSTRAINT upload_sessions_version_positive CHECK (version >= 1),
    CONSTRAINT upload_sessions_file_fk FOREIGN KEY (org_id, workspace_id, project_id, file_id)
        REFERENCES files (org_id, workspace_id, project_id, id) ON DELETE RESTRICT,
    CONSTRAINT upload_sessions_blob_fk FOREIGN KEY (org_id, blob_id)
        REFERENCES blobs (org_id, id) ON DELETE RESTRICT
);

-- One session per user and Idempotency-Key.
CREATE UNIQUE INDEX upload_sessions_idempotency_idx
    ON upload_sessions (created_by_user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;
-- Active sessions per user and organization (caps) and the expiry scan.
CREATE INDEX upload_sessions_active_user_idx ON upload_sessions (created_by_user_id)
    WHERE state IN ('created', 'receiving');
CREATE INDEX upload_sessions_active_org_idx ON upload_sessions (org_id, expires_at)
    WHERE state IN ('created', 'receiving', 'stored');
CREATE INDEX upload_sessions_file_idx ON upload_sessions (file_id);
