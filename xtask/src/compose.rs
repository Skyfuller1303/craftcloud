//! `cargo xtask compose-secrets [<dir>] [--domain <name>] [--tls-internal]
//! [--http-port <n>] [--https-port <n>]`: writes the `.env` file of the Docker
//! Compose stack in `deploy/compose` (or `<dir>`).
//!
//! The file holds the public settings (domain, ports, TLS mode, public URL)
//! and freshly generated random secrets: three database passwords, the
//! bootstrap token, the metrics token and the Base64 key that encrypts the
//! two-factor secrets (`CC_SECRET_TWO_FACTOR_KEY`, 32 random bytes). The database URLs are not stored:
//! `deploy/compose/secrets-init.sh` builds them from the role passwords. Compose hands
//! each secret to a service as a file in `/run/secrets` (see `compose.yaml`).
//! The command never overwrites an existing file, creates it with mode 0600
//! on unix and never prints a secret value. Randomness comes from the same
//! operating system source the server uses for its tokens.

use std::fmt::Write as _;
use std::fs::OpenOptions;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use craftcloud_auth::OpaqueToken;

const USAGE: &str = "usage: cargo xtask compose-secrets [<dir>] [--domain <name>] [--tls-internal] [--http-port <n>] [--https-port <n>]";

#[derive(Debug, PartialEq, Eq)]
struct Options {
    dir: PathBuf,
    domain: String,
    tls_internal: bool,
    http_port: u16,
    https_port: u16,
}

fn parse_options(root: &Path, args: &[String]) -> Result<Options, String> {
    let mut options = Options {
        dir: root.join("deploy").join("compose"),
        domain: "localhost".to_owned(),
        tls_internal: false,
        http_port: 80,
        https_port: 443,
    };
    let mut dir_seen = false;
    let mut iter = args.iter();
    while let Some(arg) = iter.next() {
        match arg.as_str() {
            "--domain" => {
                options.domain = iter.next().ok_or("--domain needs a value")?.clone();
            }
            "--tls-internal" => options.tls_internal = true,
            "--http-port" => options.http_port = parse_port(iter.next())?,
            "--https-port" => options.https_port = parse_port(iter.next())?,
            flag if flag.starts_with("--") => return Err(format!("unknown option {flag}")),
            path if !dir_seen => {
                options.dir = PathBuf::from(path);
                dir_seen = true;
            }
            _ => return Err("too many arguments".to_owned()),
        }
    }
    validate_domain(&options.domain)?;
    if options.http_port == options.https_port {
        return Err("--http-port and --https-port must differ".to_owned());
    }
    Ok(options)
}

fn parse_port(value: Option<&String>) -> Result<u16, String> {
    let value = value.ok_or("a port option needs a value")?;
    match value.parse::<u16>() {
        Ok(port) if port > 0 => Ok(port),
        _ => Err(format!("{value:?} is not a port (1 to 65535)")),
    }
}

/// A DNS name (or literal IPv4 address) in plain ASCII: dot-separated labels of
/// 1 to 63 letters, digits or hyphens, none starting or ending with a hyphen,
/// at most 253 characters in total. No scheme, port, path or bracket syntax that
/// would break the generated URL or the Caddyfile.
fn validate_domain(domain: &str) -> Result<(), String> {
    let valid = domain.len() <= 253
        && domain.split('.').all(|label| {
            (1..=63).contains(&label.len())
                && !label.starts_with('-')
                && !label.ends_with('-')
                && label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        });
    if valid {
        Ok(())
    } else {
        Err(format!(
            "{domain:?} is not a valid domain name (labels of 1 to 63 letters, digits and '-', not starting or ending with '-', separated by single dots, at most 253 characters)"
        ))
    }
}

/// The text of the `.env` file for fixed secret values (separate from
/// the random generation so tests can compare it).
fn render_env(options: &Options, secrets: &Secrets) -> String {
    let public_url = if options.https_port == 443 {
        format!("https://{}", options.domain)
    } else {
        format!("https://{}:{}", options.domain, options.https_port)
    };
    let tls_mode = if options.tls_internal {
        "internal"
    } else {
        "acme"
    };
    let mut out = String::new();
    // `write!` into a String cannot fail.
    let _ = write!(
        out,
        "# Generated by `cargo xtask compose-secrets`. CONTAINS SECRETS: keep mode 0600,\n\
         # never commit, back it up like a password store.\n\
         \n\
         CRAFTCLOUD_DOMAIN={domain}\n\
         CRAFTCLOUD_PUBLIC_URL={public_url}\n\
         CRAFTCLOUD_HTTP_PORT={http}\n\
         CRAFTCLOUD_HTTPS_PORT={https}\n\
         # acme: public certificate from Let's Encrypt; internal: Caddy's own CA (testing).\n\
         CRAFTCLOUD_TLS_MODE={tls_mode}\n\
         \n\
         CC_SECRET_DB_SUPERUSER_PASSWORD={superuser}\n\
         CC_SECRET_DB_OWNER_PASSWORD={owner}\n\
         CC_SECRET_DB_RUNTIME_PASSWORD={runtime}\n\
         CC_SECRET_BOOTSTRAP={bootstrap}\n\
         CC_SECRET_METRICS_TOKEN={metrics}\n\
         # Encrypts two-factor secrets. A restored database needs this same key: keep a\n\
         # separate protected copy, it is not part of any backup.\n\
         CC_SECRET_TWO_FACTOR_KEY={two_factor_key}\n",
        domain = options.domain,
        http = options.http_port,
        https = options.https_port,
        superuser = secrets.superuser,
        owner = secrets.owner,
        runtime = secrets.runtime,
        bootstrap = secrets.bootstrap,
        metrics = secrets.metrics,
        two_factor_key = secrets.two_factor_key,
    );
    out
}

struct Secrets {
    superuser: String,
    owner: String,
    runtime: String,
    bootstrap: String,
    metrics: String,
    /// Standard Base64 (with padding) of 32 random bytes, the format of
    /// `CRAFTCLOUD_SECRET_KEY_FILE`.
    two_factor_key: String,
}

/// Re-encodes a 43-character URL-safe, unpadded Base64 string of 32 bytes
/// (the shape of `OpaqueToken`) as standard padded Base64.
fn standard_base64(url_safe: &str) -> String {
    let mut out: String = url_safe
        .chars()
        .map(|c| match c {
            '-' => '+',
            '_' => '/',
            other => other,
        })
        .collect();
    out.push('=');
    out
}

impl Secrets {
    /// Six independent 256-bit values (43 URL-safe characters each, which
    /// also satisfies the 32-character minimum of the bootstrap and metrics tokens;
    /// the two-factor key is the same entropy in standard Base64).
    fn generate() -> Result<Self, String> {
        let one = || {
            OpaqueToken::generate()
                .map(|token| token.expose().to_owned())
                .map_err(|err| err.to_string())
        };
        Ok(Self {
            superuser: one()?,
            owner: one()?,
            runtime: one()?,
            bootstrap: one()?,
            metrics: one()?,
            two_factor_key: standard_base64(&one()?),
        })
    }
}

fn create_private_file(path: &Path) -> std::io::Result<std::fs::File> {
    let mut options = OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(0o600);
    }
    options.open(path)
}

pub fn run(root: &Path, args: &[String]) -> ExitCode {
    let options = match parse_options(root, args) {
        Ok(options) => options,
        Err(message) => {
            eprintln!("compose-secrets: {message}\n{USAGE}");
            return ExitCode::from(2);
        }
    };
    let secrets = match Secrets::generate() {
        Ok(secrets) => secrets,
        Err(message) => {
            eprintln!("compose-secrets: {message}");
            return ExitCode::FAILURE;
        }
    };
    if let Err(err) = std::fs::create_dir_all(&options.dir) {
        eprintln!(
            "compose-secrets: cannot create {}: {err}",
            options.dir.display()
        );
        return ExitCode::FAILURE;
    }
    let path = options.dir.join(".env");
    let written = create_private_file(&path)
        .and_then(|mut file| file.write_all(render_env(&options, &secrets).as_bytes()));
    match written {
        Ok(()) => {
            println!(
                "wrote {} (domain {}, TLS {}); it contains secrets, do not commit or share it",
                path.display(),
                options.domain,
                if options.tls_internal {
                    "internal"
                } else {
                    "acme"
                }
            );
            if cfg!(not(unix)) {
                println!("note: file permissions were not restricted on this platform");
            }
            ExitCode::SUCCESS
        }
        Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => {
            eprintln!(
                "compose-secrets: {} already exists and is not overwritten; move it away to generate new secrets",
                path.display()
            );
            ExitCode::FAILURE
        }
        Err(err) => {
            eprintln!("compose-secrets: cannot write {}: {err}", path.display());
            // Do not leave a half-written secrets file behind.
            let _ = std::fs::remove_file(&path);
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| (*s).to_owned()).collect()
    }

    fn fixed() -> Secrets {
        Secrets {
            superuser: "S".into(),
            owner: "O".into(),
            runtime: "R".into(),
            bootstrap: "B".into(),
            metrics: "M".into(),
            two_factor_key: "K".into(),
        }
    }

    #[test]
    fn defaults_and_flags() {
        let root = Path::new("/repo");
        let options = parse_options(root, &args(&[])).unwrap();
        assert_eq!(options.dir, root.join("deploy").join("compose"));
        assert_eq!(options.domain, "localhost");
        assert!(!options.tls_internal);
        assert_eq!((options.http_port, options.https_port), (80, 443));

        let options = parse_options(
            root,
            &args(&[
                "out",
                "--domain",
                "cloud.example.org",
                "--tls-internal",
                "--https-port",
                "18443",
                "--http-port",
                "18080",
            ]),
        )
        .unwrap();
        assert_eq!(options.dir, PathBuf::from("out"));
        assert_eq!(options.domain, "cloud.example.org");
        assert!(options.tls_internal);
        assert_eq!((options.http_port, options.https_port), (18080, 18443));
    }

    #[test]
    fn bad_input_is_rejected() {
        let root = Path::new("/repo");
        for bad in [
            &["--domain"][..],
            &["--domain", "https://x.org"],
            &["--domain", "x.org:443"],
            &["--domain", ""],
            &["--domain", "-x.org"],
            &["--http-port", "0"],
            &["--https-port", "70000"],
            &["--https-port", "80"],
            &["--bogus"],
            &["a", "b"],
        ] {
            assert!(parse_options(root, &args(bad)).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn domain_labels_are_validated() {
        let long_label = "a".repeat(64);
        let max_label = "a".repeat(63);
        let long_name = format!("{max_label}.{max_label}.{max_label}.{}", "b".repeat(61));
        assert_eq!(long_name.len(), 253);
        for good in [
            "localhost",
            "cloud.example.org",
            "127.0.0.1",
            "a-b.c",
            max_label.as_str(),
            long_name.as_str(),
        ] {
            assert!(validate_domain(good).is_ok(), "{good}");
        }
        let too_long = format!("{long_name}c");
        for bad in [
            "",
            "a..b",
            ".a",
            "a.",
            "-a.org",
            "a-.org",
            "a.-b",
            "a b",
            "ä.org",
            "a_b.org",
            long_label.as_str(),
            too_long.as_str(),
        ] {
            assert!(validate_domain(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn env_file_has_public_settings_urls_and_secrets() {
        let root = Path::new("/repo");
        let options = parse_options(
            root,
            &args(&[
                "--domain",
                "cloud.test",
                "--tls-internal",
                "--https-port",
                "18443",
            ]),
        )
        .unwrap();
        let text = render_env(&options, &fixed());
        assert!(text.contains("CRAFTCLOUD_PUBLIC_URL=https://cloud.test:18443\n"));
        assert!(text.contains("CRAFTCLOUD_TLS_MODE=internal\n"));
        assert!(text.contains("CRAFTCLOUD_HTTP_PORT=80\n"));
        assert!(text.contains("CC_SECRET_DB_OWNER_PASSWORD=O\n"));
        assert!(text.contains("CC_SECRET_DB_RUNTIME_PASSWORD=R\n"));
        assert!(
            !text.contains("DB_OWNER_URL"),
            "URLs are derived by secrets-init.sh"
        );
        let default = render_env(&parse_options(root, &args(&[])).unwrap(), &fixed());
        assert!(default.contains("CRAFTCLOUD_PUBLIC_URL=https://localhost\n"));
        assert!(default.contains("CRAFTCLOUD_TLS_MODE=acme\n"));
    }

    #[test]
    fn generated_secrets_are_long_distinct_and_url_safe() {
        let secrets = Secrets::generate().unwrap();
        let all = [
            &secrets.superuser,
            &secrets.owner,
            &secrets.runtime,
            &secrets.bootstrap,
            &secrets.metrics,
        ];
        for (index, value) in all.iter().enumerate() {
            assert!(value.len() >= 32);
            assert!(
                value
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
            );
            for other in all.iter().skip(index + 1) {
                assert_ne!(value, other);
            }
        }
    }

    #[test]
    fn two_factor_key_is_standard_base64_of_32_bytes() {
        let secrets = Secrets::generate().unwrap();
        let key = &secrets.two_factor_key;
        assert_eq!(key.len(), 44);
        assert!(key.ends_with('='));
        assert!(
            key[..43]
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'+' || b == b'/')
        );
        assert_ne!(key, &secrets.metrics);
        assert_eq!(standard_base64("-_-_"), "+/+/=");
    }

    #[test]
    fn an_existing_file_is_never_overwritten() {
        let dir = std::env::temp_dir().join(format!("cc-compose-secrets-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join(".env");
        let _ = std::fs::remove_file(&path);
        drop(create_private_file(&path).unwrap());
        std::fs::write(&path, "keep").unwrap();
        let err = create_private_file(&path).unwrap_err();
        assert_eq!(err.kind(), std::io::ErrorKind::AlreadyExists);
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "keep");
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
